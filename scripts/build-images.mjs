// Re-runnable image build. Usage: node scripts/build-images.mjs [--check] [--help]   (npm run images / images:check)
//  Settings live in scripts/images.config.json: widths, quality, strictOrientation, excludeSlots (a slot can have a file in
//  assets-source/ and still keep its SVG placeholder), roundTwoOnly (slots usable only with a given photo), alts. See docs/IMAGES.md.
//  1. validates assets-source/ against docs/IMAGE_SLOTS.md + SOURCES.csv (scripts/images-lib.mjs);
//     a file with any problem is NOT used and its slot keeps the SVG placeholder;
//  2. writes WebP widths (480/800/1200/1600/2000, never above the source width) to src/assets/photos/,
//     only for sources that changed (sha1 kept in build-cache.json);
//  3. writes photos.json (app) + build-cache.json + photos.css (dominant-colour placeholder classes) in src/assets/photos/,
//     images.json and CREDITS.md in the repo root, docs/IMAGE_STATUS.md.
// Only the processed files are committed; originals live in assets-source/ already.
import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import sharp from 'sharp'
import { validate, config, root } from './images-lib.mjs'

if (process.argv.includes('--help')) {
  console.log(fs.readFileSync(new URL(import.meta.url), 'utf8').split('\n').filter((l) => l.startsWith('//')).slice(0, 12).join('\n'))
  process.exit(0)
}
const check = process.argv.includes('--check')
const out = path.join(root, 'src/assets/photos')
fs.mkdirSync(out, { recursive: true })
const manifestPath = path.join(out, 'build-cache.json') // sha1 + bytes per photo (not bundled)
const old = fs.existsSync(manifestPath) ? JSON.parse(fs.readFileSync(manifestPath, 'utf8')) : {}
const settingsKey = JSON.stringify([config.widths, config.quality])

const sizesFor = (base) =>
  base.startsWith('product-')
    ? '(min-width: 1200px) 448px, (min-width: 810px) 33vw, 50vw'
    : base.startsWith('collection-')
      ? '(min-width: 810px) 50vw, 100vw'
      : '100vw'

const r = await validate()
const rejected = r.files.filter((f) => !f.ok && !f.excluded)
const excluded = r.files.filter((f) => f.excluded)
console.log(`${r.files.filter((f) => f.ok).length} valid, ${excluded.length} excluded by config, ${rejected.length} rejected, ${r.missing.length} placeholders kept`)
for (const f of rejected) console.log(`REJECTED ${f.file}: ${f.problems.join('; ')}`)
if (check) process.exit(rejected.length ? 1 : 0)

const manifest = {}
for (const f of r.files.filter((f) => f.ok)) {
  const src = path.join(root, 'assets-source', f.file)
  const sha = crypto.createHash('sha1').update(fs.readFileSync(src)).digest('hex')
  const prev = old[f.slot]
  const widths = config.widths.filter((w) => w <= f.width)
  if (!widths.length) widths.push(f.width)
  const names = widths.map((w) => `${f.slot}-${w}.webp`)
  if (prev && prev.sha === sha && prev.settings === settingsKey && names.every((n) => fs.existsSync(path.join(out, n)))) {
    manifest[f.slot] = prev
    continue
  }
  const bytes = {}
  for (const [i, w] of widths.entries()) {
    const info = await sharp(src).rotate().resize({ width: w, withoutEnlargement: true }).webp({ quality: config.quality, effort: 5, smartSubsample: true }).toFile(path.join(out, names[i]))
    bytes[w] = info.size
    if (i === widths.length - 1) manifest[f.slot] = { w: info.width, h: info.height }
  }
  const { dominant } = await sharp(src).rotate().resize(64).stats()
  const hex = '#' + [dominant.r, dominant.g, dominant.b].map((v) => v.toString(16).padStart(2, '0')).join('')
  Object.assign(manifest[f.slot], { widths, bytes, color: hex, sizes: sizesFor(f.slot), sha, settings: settingsKey })
  console.log(`built ${f.slot}: ${widths.join('/')}`)
}

for (const slot of Object.keys(manifest)) manifest[slot].alt = config.alts[slot] ?? ''
// product photos and the founder photo are content images: they need an alt that describes the real photo
// (everything else is decorative, alt=""). A new file without one stays decorative and is listed here.
const needAlt = Object.keys(manifest).filter((s) => (s.startsWith('product-') || s === 'founder') && !manifest[s].alt)
for (const s of needAlt) console.log(`WARNING: ${s} has no alt in scripts/images.config.json (alts), set one that describes the photo`)

// remove outputs of slots that are no longer valid
const keep = new Set(Object.entries(manifest).flatMap(([slot, m]) => m.widths.map((w) => `${slot}-${w}.webp`)))
for (const file of fs.readdirSync(out)) if (file.endsWith('.webp') && !keep.has(file)) fs.unlinkSync(path.join(out, file))

fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 1) + '\n')
// compact file the app imports (src/assets/photos/index.js)
fs.writeFileSync(
  path.join(out, 'photos.json'),
  JSON.stringify(Object.fromEntries(Object.entries(manifest).map(([slot, m]) => [slot, { widths: m.widths, w: m.w, h: m.h, sizes: m.sizes, alt: m.alt }]))) + '\n',
)
fs.writeFileSync(
  path.join(out, 'photos.css'),
  '/* generated by scripts/build-images.mjs: dominant-colour placeholder behind each photo while it loads */\n' +
    Object.entries(manifest).map(([slot, m]) => `.phc-${slot}{background-color:${m.color}}`).join('\n') + '\n',
)

// images.json + CREDITS.md from SOURCES.csv (only for files that are used)
const used = r.files.filter((f) => f.ok)
const images = used.map((f) => ({
  slot: f.slot,
  file: `assets-source/${f.file}`,
  originalSize: `${f.width}×${f.height}`,
  outputs: manifest[f.slot].widths.map((w) => `src/assets/photos/${f.slot}-${w}.webp`),
  site: f.source.source_site,
  photoPage: f.source.photo_page_url,
  author: f.source.author_name,
  authorProfile: f.source.author_profile_url,
  license: f.source.license_name,
  licenseUrl: f.source.license_page_url,
  dateChecked: f.source.date_checked,
}))
fs.writeFileSync(path.join(root, 'images.json'), JSON.stringify(images, null, 2) + '\n')
const byPhoto = new Map()
for (const i of images) byPhoto.set(i.photoPage, [...(byPhoto.get(i.photoPage) ?? []), i])
const credits = [
  '# Photo credits',
  '',
  'Product and collection photographs on this site come from the sources below. Generated from `SOURCES.csv` by `scripts/build-images.mjs`; do not edit by hand.',
  'Attribution is not required by these licenses, but credit is given here. Re-check the license page of each source before selling or redistributing this project.',
  '',
  '| Slots | Photographer | Site | License | Photo page |',
  '|---|---|---|---|---|',
  ...[...byPhoto.values()].map((list) => {
    const i = list[0]
    return `| ${list.map((x) => x.slot).join(', ')} | [${i.author}](${i.authorProfile}) | ${i.site} | [${i.license}](${i.licenseUrl}) | [photo](${i.photoPage}) |`
  }),
  '',
]
fs.writeFileSync(path.join(root, 'CREDITS.md'), credits.join('\n'))

// status doc
const kb = (n) => (n / 1024).toFixed(0)
const total = Object.values(manifest).reduce((s, m) => s + Object.values(m.bytes ?? {}).reduce((a, b) => a + b, 0), 0)
const status = [
  '# Image status (generated by scripts/build-images.mjs)',
  '',
  `${used.length} of ${Object.keys(r.slots).length} slots use a real photo; ${r.missing.length} keep their SVG placeholder. Processed WebP total ${(total / 1048576).toFixed(1)} MB.`,
  '',
  '## Rejected files (not used)',
  ...(rejected.length ? rejected.map((f) => `- \`${f.file}\`: ${f.problems.join('; ')}`) : ['- none']),
  '',
  '## Excluded by config (file kept in assets-source/, slot keeps its placeholder)',
  ...(excluded.length ? excluded.map((f) => `- \`${f.file}\``) : ['- none']),
  '',
  '## Warnings on used files',
  ...used.flatMap((f) => f.warnings.map((w) => `- \`${f.file}\`: ${w}`)),
  '',
  '## Content photos without an alt text (set one in scripts/images.config.json)',
  needAlt.length ? needAlt.join(', ') : 'none',
  '',
  '## Slots without a valid file',
  r.missing.join(', '),
  '',
  '## Weight per photo (KB, 1200 px version)',
  ...Object.entries(manifest).map(([slot, m]) => `- ${slot}: ${kb(m.bytes[1200] ?? m.bytes[Math.max(...m.widths)])}`),
  '',
]
fs.writeFileSync(path.join(root, 'docs/IMAGE_STATUS.md'), status.join('\n'))
console.log(`done: ${(total / 1048576).toFixed(1)} MB of WebP in src/assets/photos/`)
